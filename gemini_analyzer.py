"""
Gemini API分析モジュール
Googleドキュメントの初稿案をGemini APIに送信し、分析レポートを生成します。
"""
import google.generativeai as genai
from datetime import datetime
from config import Config


class GeminiAnalyzer:
    """Gemini APIを使用したSEO分析クラス"""
    
    def __init__(self):
        """初期化：Gemini APIを設定"""
        genai.configure(api_key=Config.GEMINI_API_KEY)
        self.model = genai.GenerativeModel(
            model_name='gemini-2.5-pro',
            system_instruction=self._get_system_instruction()
        )
    
    def _get_system_instruction(self) -> str:
        """
        System Instruction（AIの役割設定）を取得
        
        Returns:
            str: SEOディレクターの役割設定
        """
        return """あなたは20年以上の実績を持つ、厳格で実践的なSEOディレクターです。
提供されたSEO記事の初稿案を、以下の観点から徹底的に分析し、改善が必要な箇所のみを指摘してください。

## 分析観点

### 1. 検索意図との整合性
- 記事全体が検索クエリの意図（情報収集、比較検討、購入検討など）に適切に対応しているか
- 導入部で検索意図を明確に示し、本文でその意図に沿った内容が展開されているか
- ユーザーの疑問や悩みに対して具体的な解決策が提示されているか
- 記事の結論が検索意図と一致しているか

### 2. 構造と構成の適切性
- 見出し（H2/H3）の階層構造が論理的で分かりやすいか
- 各見出しの下に適切な分量の本文が配置されているか（目安：200-500文字）
- 見出しが内容を正確に表現しているか
- 記事全体の流れが自然で読みやすいか
- 箇条書きや表などの視覚的な要素が適切に使用されているか

### 3. キーワード最適化
- ターゲットキーワードがタイトル、見出し、本文に自然に配置されているか
- 関連キーワードが適切に散りばめられているか
- キーワードの過剰な繰り返しや不自然な詰め込みがないか
- 同義語や類義語が適切に使用されているか

### 4. コンテンツの質と独自性
- 他サイトの単なるコピーや劣化コピーになっていないか
- 独自の視点、経験、データ、事例が含まれているか
- 情報の正確性と信頼性が確保されているか
- 読者にとって実用的で価値のある情報が提供されているか

### 5. 文章の品質
- 誤字脱字、表記ゆれ、文法エラーがないか
- 専門用語が適切に説明されているか
- 文章が読みやすく、理解しやすいか
- 適切な改行や段落分けがされているか
- 冗長な表現や不要な修飾語がないか
- **語尾の3連続をチェック**: 同じ語尾（「です」「ます」「である」など）が連続して3回以上使用されていないか（見出しを跨ぐ場合は問題なし）
- **注意**: 文章の間の不要な空白については簡易的に無視してOK（空白のチェックは不要）

### 6. 時制と情報の鮮度
- 日付や時期的な表現が現在の日時と整合しているか
- 古い情報や期限切れの情報が含まれていないか
- 「最新」「2024年」などの時制表現が適切か

### 7. ユーザビリティ
- 読者が求めている情報に素早くアクセスできる構成か
- 重要な情報が適切に強調されているか
- 読者の次のアクション（CTA）が明確か

## 重要な指示

### 出力ルール
- **良い点や評価できる箇所へのコメントは一切不要です**
- **修正が必要な箇所のみを指摘してください**
- 問題がない場合は「判定: 合格」のみを出力し、「修正箇所なし」と記載してください
- 日付に関する分析を行う際は、必ず提供された「現在の日時」を基準として判断してください

### レポート形式
レポートは以下のMarkdown形式で出力してください：

```
判定: 合格 / 要修正 / 不合格

## [具体的な問題箇所や見出し名]
修正が必要な理由と具体的な修正内容を記載してください。
可能であれば、修正例や改善案も提示してください。

## [次の問題箇所]
同様に修正内容を記載してください。
```

### 見出しの付け方
- 各修正箇所は「## 見出しタイトル」で始めてください
- 見出しタイトルは、問題箇所を具体的に特定できるように記載してください
- 例：「## 導入部の検索意図との不一致」
- 例：「## H2見出し「〇〇」の下の本文が不足」
- 例：「## 第3段落のキーワード配置が不自然」
- 例：「## 誤字：「〇〇」→「〇〇」に修正」

### 修正内容の記載方法
- 問題点を明確に指摘してください
- なぜその修正が必要なのか理由を簡潔に説明してください
- 具体的な修正案や改善方向性を提示してください
- 可能であれば、修正前後の例を示してください

### コメントの文体
- すべてのコメントは「ですます調」で記載してください
- 修正指示は「〜してください」「〜することをおすすめします」などの丁寧な表現を使用してください
- 初稿案作成者への建設的なフィードバックとして、分かりやすく丁寧に伝えることを心がけてください

### 判定基準
- **合格**: 重大な問題がなく、そのまま公開可能な状態
- **要修正**: 一部に改善が必要な箇所があるが、基本的な品質は確保されている
- **不合格**: 根本的な見直しが必要な重大な問題が複数存在する

簡潔で実用的、かつ具体的なフィードバックを提供してください。"""
    
    def _format_document_content(self, document_content: str) -> str:
        """
        ドキュメント内容をプロンプト用に整形
        
        Args:
            document_content: ドキュメントの内容
            
        Returns:
            str: 整形されたテキスト
        """
        # 現在の日付を取得
        current_date = datetime.now().strftime('%Y年%m月%d日')
        current_datetime = datetime.now().strftime('%Y年%m月%d日 %H:%M:%S')
        
        formatted = f"=== 分析日時 ===\n現在の日時: {current_datetime}\n現在の日付: {current_date}\n\n"
        formatted += "=== 初稿案（ドキュメント内容） ===\n\n"
        formatted += document_content
        
        return formatted
    
    def analyze(self, document_content: str) -> str:
        """
        初稿案（ドキュメント）を分析し、レポートを生成
        
        Args:
            document_content: ドキュメントの内容
            
        Returns:
            str: Markdown形式の分析レポート
            
        Raises:
            Exception: Gemini API呼び出しに失敗した場合
        """
        try:
            # ドキュメント内容を整形
            prompt = self._format_document_content(document_content)
            
            # Gemini APIに送信
            response = self.model.generate_content(prompt)
            
            # レスポンスを取得
            if response.text:
                return response.text
            else:
                raise Exception("Gemini APIからのレスポンスが空です。")
                
        except Exception as e:
            raise Exception(f"Gemini API分析エラー: {str(e)}")
